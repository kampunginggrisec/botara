/**
 * API <-> UI parity classification (audit R1).
 *
 * Every route the API exposes must be accounted for in exactly one of
 * two ways:
 *   (a) referenced by the web client (apps/web/src/api.ts), the widget
 *       (apps/web/src/widget.ts), or the SPA sources — the parity guard
 *       test (route-parity.test.ts) extracts those references, or
 *   (b) listed HERE with a class and a reason it has no SPA caller.
 *
 * Classes:
 *   WEBHOOK  — called by an external provider or by a browser
 *              navigation the provider initiates (webhook handshakes +
 *              event posts, OAuth callbacks, public redirect/status
 *              URLs the API mints for the outside world).
 *   API-ONLY — deliberately operator/tooling surface: health probes,
 *              the OpenAPI document, and single-fetch by-id endpoints
 *              kept for API consumers while the SPA works through the
 *              list + mutation endpoints on the same paths.
 *
 * Keys are "METHOD /normalized/path" with path params normalized to {}.
 * Adding a route without a UI caller? Add its entry here in the same
 * change — the guard fails otherwise. The human-readable mirror of this
 * table lives in docs/api-ui-parity.md.
 */
